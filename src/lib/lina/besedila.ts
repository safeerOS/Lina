export const besedila = { sl, en };

export type Jezik = "sl" | "en";
export type IzbiraJezika = "sistem" | Jezik;
export const KLJUC_JEZIKA = "lina-jezik";

/**
 * Jezik vmesnika. Nastavi ga samo brskalnik (JezikVmesnika v __root.tsx po izbiri v Nastavitvah); streznik ga ne nastavi,
 * zato besedila za klicatelje in glas ostanejo slovenska.
 */
let trenutniJezik: Jezik = "sl";
export function jezikVmesnika(): Jezik {
  return trenutniJezik;
}
export function nastaviJezikVmesnika(j: Jezik): void {
  trenutniJezik = j;
}
export function razberiIzbiroJezika(s: string | null): IzbiraJezika {
  return s === "sl" || s === "en" ? s : "sistem";
}
/** »Kot sistem«: slovenscina za slovenski sistem, sicer anglescina; brez podatka ostane slovenscina. */
export function razresiJezik(izbira: IzbiraJezika, sistemski: string | undefined): Jezik {
  if (izbira !== "sistem") return izbira;
  if (!sistemski) return "sl";
  return sistemski.toLowerCase().startsWith("sl") ? "sl" : "en";
}
/**
 * Sporocilo streznika (izjema ali {sporocilo}) za prikaz: streznik govori slovensko (jezik pozna samo brskalnik), zato ga angleski
 * vmesnik pokaze za angleskim uvodom, ne gole slovenscine. Prazno sporocilo je splosna napaka v jeziku vmesnika.
 */
export function sporociloStreznika(sporocilo: string | null | undefined, j: Jezik = trenutniJezik): string {
  const s = (sporocilo ?? "").trim();
  if (!s) return t("uiNapakaSplosna", j);
  // ze prevedeno besedilo vmesnika (npr. throw new Error(t(...))) ostane brez uvoda
  if (j === "sl" || Object.values(besedila[j]).includes(s)) return s;
  return `${t("uiNapakaStreznika", j)} ${s}`;
}
/** Izjema -> besedilo za vmesnik. Napake brskalnika (TypeError: Failed to fetch; DOMException: mikrofon) niso besedilo streznika. */
export function sporociloNapake(cause: unknown, j: Jezik = trenutniJezik): string {
  const brskalnik = cause instanceof TypeError || (typeof DOMException !== "undefined" && cause instanceof DOMException);
  return sporociloStreznika(cause instanceof Error && !brskalnik ? cause.message : "", j);
}
export function lokalizacija(j: Jezik = trenutniJezik): string {
  return j === "en" ? "en-GB" : "sl-SI";
}

/** Privzeto jezik vmesnika (na strezniku vedno slovenscina). en pusti anglescino. */
export function t(kljuc: Beseda, jezik: Jezik = trenutniJezik): string {
  return besedila[jezik][kljuc];
}
